#!/usr/bin/env bash
# Writes data/releases.yaml: the latest GitHub release tag of each product in
# data/products.yaml, so the portal always shows the released version.
#
#   scripts/releases.sh           CI: fails if a release cannot be read
#   scripts/releases.sh --soft    local: keeps going, the templates then fall
#                                 back to `version` in data/products.yaml
#
# Uses $GH_TOKEN / $GITHUB_TOKEN when set (higher API rate limit).
set -euo pipefail
cd "$(dirname "$0")/.."

soft=false; [ "${1:-}" = --soft ] && soft=true
token=${GH_TOKEN:-${GITHUB_TOKEN:-}}
out=data/releases.yaml
tmp=$(mktemp); trap 'rm -f "$tmp"' EXIT

echo "# generated by scripts/releases.sh, do not edit" > "$tmp"
for repo in $(sed -nE 's/^ +repo: *([^ ]+) *$/\1/p' data/products.yaml); do
  if tag=$(curl -fsSL ${token:+-H "Authorization: Bearer $token"} \
             "https://api.github.com/repos/$repo/releases/latest" | jq -er .tag_name); then
    echo "\"$repo\": $tag" >> "$tmp"
    echo "  $repo $tag"
  elif $soft; then
    echo "  $repo: latest release not found, using data/products.yaml" >&2
  else
    echo "::error::$repo: cannot read its latest release" >&2; exit 1
  fi
done
mv "$tmp" "$out"; trap - EXIT
